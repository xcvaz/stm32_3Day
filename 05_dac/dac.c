/* USER CODE BEGIN 0 */
static void Generate_Sine_LUT(void)
{
  for (uint32_t i = 0; i < SINE_SAMPLES; i++)
  {
    float angle  = (2.0f * PI * (float)i) / (float)SINE_SAMPLES;
    float sample = (float)DAC_MID_VALUE + (float)(DAC_MID_VALUE - 1U) * sinf(angle);

    /* round to nearest instead of truncating, clamp for safety */
    if (sample < 0.0f) sample = 0.0f;
    if (sample > (float)DAC_MAX_VALUE) sample = (float)DAC_MAX_VALUE;

    sine_lut[i] = (uint16_t)(sample + 0.5f);
  }
}
