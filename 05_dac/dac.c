/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_DAC1_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */
  /* Build the sine table once at startup (no per-sample sinf() calls later) */
  Generate_Sine_LUT();

  /* Start DAC Channel 1 */
   if (HAL_DAC_Start(&hdac1, DAC_CHANNEL_1) != HAL_OK)
   {
     Error_Handler();
   }

   /* Set initial DAC value */
   if (HAL_DAC_SetValue(&hdac1, DAC_CHANNEL_1, DAC_ALIGN_12B_R, DAC_MID_VALUE) != HAL_OK)
   {
     Error_Handler();
   }

   /* Send startup message over UART */
   sprintf(uart_buf, "\r\nSTM32G431 DAC Sine Wave Started\r\n");
   HAL_UART_Transmit(&huart2, (uint8_t *)uart_buf, strlen(uart_buf), HAL_MAX_DELAY);

   sprintf(uart_buf, "DAC Output: PA4\r\nUART: USART2 115200 baud\r\nSine samples: %d\r\n\r\n", SINE_SAMPLES);
   HAL_UART_Transmit(&huart2, (uint8_t *)uart_buf, strlen(uart_buf), HAL_MAX_DELAY);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	    /* Look up current sine wave sample (precomputed, no float math here) */
	    dac_value = sine_lut[sample_number];

	    /* Write output value to DAC */
	    if (HAL_DAC_SetValue(&hdac1, DAC_CHANNEL_1, DAC_ALIGN_12B_R, dac_value) != HAL_OK)
	    {
	      Error_Handler();
	    }

	    /* Print every sample via UART in plain CSV format for a serial plotter
	       (Arduino Serial Plotter, PlotJuggler, Serial Studio, Teleplot, etc.) */
	    uint32_t millivolts = (dac_value * 3300U) / DAC_MAX_VALUE;
	    sprintf(uart_buf, "%lu,%lu\r\n", dac_value, millivolts);
	    HAL_UART_Transmit(&huart2, (uint8_t *)uart_buf, strlen(uart_buf), HAL_MAX_DELAY);

	    /* Advance sample counter */
	    sample_number++;
	    if (sample_number >= SINE_SAMPLES)
	    {
	      sample_number = 0;
	    }

	    /* Delay controlling frequency */
	    HAL_Delay(SAMPLE_DELAY_MS);
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

